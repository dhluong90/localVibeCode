def query_ollama(prompt: str, system: str = "") -> Tuple[str, int, int, float]:
    payload = {
        "model": MODEL_NAME,
        "prompt": prompt,
        "system": system or "You are an expert full-stack developer. Write ONLY clean, compilable, production-ready code. Wrap the code in standard code fences.",
        "stream": False,
        "options": {
            "temperature": 0.1,
            "num_ctx": 8192,
        },
    }
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        OLLAMA_URL, data=data, headers={"Content-Type": "application/json"}
    )
    t0 = time.time()
    try:
        with urllib.request.urlopen(req, timeout=180) as resp:
            res_json = json.loads(resp.read().decode("utf-8"))
            elapsed = time.time() - t0
            response_text = res_json.get("response", "")
            prompt_tokens = res_json.get("prompt_eval_count", 0)
            completion_tokens = res_json.get("eval_count", 0)
            return response_text, prompt_tokens, completion_tokens, elapsed
    except Exception as e:
        elapsed = time.time() - t0
        return f"[ERROR] Failed to call Ollama: {str(e)}", 0, 0, elapsed


def extract_code(text: str, default_lang: str = "") -> str:
    pattern = r"```(?:\w+)?\n(.*?)```"
    matches = re.findall(pattern, text, re.DOTALL)
    if matches:
        # Return longest matching block
        return max(matches, key=len).strip()
    return text.strip()


def run_command(cmd: List[str], cwd: Path) -> Tuple[bool, str]:
    try:
        res = subprocess.run(
            cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=60
        )
        return res.returncode == 0, res.stdout
    except Exception as e:
        return False, str(e)


