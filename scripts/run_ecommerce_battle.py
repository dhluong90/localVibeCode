            f"- **Target File:** `{record.target_file}`\n"
            f"- **Duration:** {record.duration_sec:.2f}s | "
            f"**Tokens:** {record.prompt_tokens} in / {record.completion_tokens} out | "
            f"**Pass@1:** {'✅ YES' if record.pass_at_1 else '❌ NO'} | "
