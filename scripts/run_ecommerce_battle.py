    def log_interaction(self, record: StepRecord):
        self.records.append(record)
        # Append JSONL
        with open(JSONL_LOG, "a", encoding="utf-8") as f:
            f.write(json.dumps(asdict(record), ensure_ascii=False) + "\n")

